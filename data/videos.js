export function formatViews(num) {
  if (num >= 1000000000) {
    return `${Math.round(num / 1000000000)}B`;
  } else if (num >= 1000000) {
    return `${Math.round(num / 1000000)}M`;
  } else if (num >= 1000) {
    return `${Math.round(num / 1000)}K`;
  }
  return `${num}`;
}

export function calculateDate(uploadedAt) {
  dayjs.extend(relativeTime);
  const result = dayjs(uploadedAt).fromNow(true);
  return result;
}

export async function fetchVideoTime(videoId) {
  try {
    const apiKey = process.env.API_KEY;
    const url = `https://www.googleapis.com/youtube/v3/videos?part=snippet&id=${videoId}&key=${apiKey}`;

    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`ERROR: ${response.status}`);
    } else {
      const data = await response.json();
      const video = data.items[0].snippet;
      const uploadedTime = video.publishedAt;
      return uploadedTime;
    }
  } catch (error) {
    throw new Error(`ERROR: ${response.status}`);
  }
}

